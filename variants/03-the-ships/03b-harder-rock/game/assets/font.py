# The boss's bar, eight cells where VARKONIA is; a cell filled by 0-8
# columns, inside a frame.
for _k in range(9):
    BARS[f"BOSS_{_k}"] = (["........", "########"] +
                          ["#" * _k + "." * (8 - _k)] * 4 +
                          ["########", "........"])


def glyph_bytes(rows):
    """Eight bytes: the rows, padded to eight columns and lines."""
    data = bytearray()
    for row in (rows + ["........"] * 8)[:8]:
        bits = (row + "........")[:8]
        data.append(int(bits.replace(".", "0").replace("#", "1"), 2))
    return bytes(data)
